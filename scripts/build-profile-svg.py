"""Stack the animated profile scenes without a Markdown gap."""
from hashlib import sha256
from pathlib import Path
import re
from xml.etree import ElementTree

assets = Path(__file__).resolve().parents[1] / "assets"


def prefix_exploring_styles(source):
    """Keep the exploration scene's selectors and animations local to it."""
    def prefix_classes(match):
        classes = " ".join(f"exploring-{name}" for name in match[1].split())
        return f'class="{classes}"'

    def prefix_css(match):
        css = re.sub(r"\.([a-zA-Z][\w-]*)", r".exploring-\1", match[1])
        names = re.findall(r"@keyframes\s+([\w-]+)", css)
        if names:
            pattern = r"(?<![\w-])(?:" + "|".join(map(re.escape, names)) + r")(?![\w-])"
            css = re.sub(pattern, lambda name: f"exploring-{name[0]}", css)
        return f"<style>{css}</style>"

    source = re.sub(r'\bclass="([^"]+)"', prefix_classes, source)
    return re.sub(r"<style>(.*?)</style>", prefix_css, source, flags=re.S)


# The scenes share one document clock. Start the exploration scene once the
# opening scene's pipe has faded in (.cc-pipe: 500ms at 37000ms).
EXPLORING_START_MS = 37500
TIME = r"(\d+(?:\.\d+)?)(ms|s)"


def to_ms(value, unit):
    return float(value) * (1000 if unit == "s" else 1)


def delay_exploring_timeline(source, offset):
    """Shift every animation delay in the exploration scene by offset ms."""
    def shift_var(match):
        return f"{match[1]}{to_ms(match[2], match[3]) + offset:g}ms"

    source = re.sub(r"(--(?:at|open|grow-at|ripe):\s*)" + TIME, shift_var, source)

    def shift_animation(match):
        parts = []
        for part in re.split(r",(?![^()]*\))", match[2]):
            times = list(re.finditer(r"(?<![\w.-])" + TIME + r"(?![\w-])", part))
            if len(times) >= 2:  # second time is the delay
                t = times[1]
                part = f"{part[:t.start()]}{to_ms(t[1], t[2]) + offset:g}ms{part[t.end():]}"
            elif "var(" not in part:  # no delay: add one
                part = f"{part.rstrip()} {offset}ms"
            parts.append(part)
        return f"{match[1]}{','.join(parts)}"

    return re.sub(r"(animation:)([^;}]+)", shift_animation, source)


scenes = []
seen_ids = set()
for name in ("profile-open-latest.svg", "profile-exploring.svg"):
    source = (assets / name).read_text(encoding="utf-8")
    root = ElementTree.fromstring(source)
    ids = {element.get("id") for element in root.iter() if element.get("id")}
    if seen_ids & ids:
        raise ValueError(f"Duplicate IDs across profile scenes: {seen_ids & ids}")
    seen_ids.update(ids)
    width, height = (int(root.attrib[key]) for key in ("width", "height"))
    if name == "profile-exploring.svg":
        source = prefix_exploring_styles(source)
        source = delay_exploring_timeline(source, EXPLORING_START_MS)
    scenes.append((width, height, source.strip()))

width = scenes[0][0]
if any(scene_width != width for scene_width, _, _ in scenes):
    raise ValueError("Profile scenes must use the same width to align the pipe.")
height = sum(scene_height for _, scene_height, _ in scenes)
lines = [
    f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
    f'viewBox="0 0 {width} {height}">',
    "  <!-- Generated by scripts/build-profile-svg.py. Edit the source scenes. -->",
]
y = 0
for _, scene_height, source in scenes:
    lines.append(source.replace("<svg ", f'<svg x="0" y="{y}" ', 1))
    y += scene_height
lines.append("</svg>")
profile = ("\n".join(lines) + "\n").encode("utf-8")
(assets / "profile.svg").write_bytes(profile)

readme = assets.parent / "README.md"
version = sha256(profile).hexdigest()[:10]
markdown = readme.read_text(encoding="utf-8")
updated, matches = re.subn(
    r"(assets/profile\.svg\?v=)[a-f0-9]+", lambda match: match[1] + version, markdown
)
if matches != 1:
    raise ValueError("Expected one versioned profile image in README.md.")
readme.write_text(updated, encoding="utf-8")
